def R(x, y, w, h, fc, ec="#e8e8e8", lw=1.5, z=2, a=1.0, hatch=None, ls="-"):
    ax.add_patch(Rectangle((x, y), w, h, fc=fc, ec=ec, lw=lw, zorder=z, alpha=a, hatch=hatch, ls=ls))
def T(x, y, s, size=10, c="white", w="bold", z=10, ha="center", va="center", rot=0, box=None):
    kw = dict(bbox=dict(boxstyle="round,pad=0.2", fc=box, ec="none", alpha=0.85)) if box else {}
    ax.text(x, y, s, fontsize=size, color=c, fontweight=w, zorder=z, ha=ha, va=va, rotation=rot, **kw)
def N(x, y, n, c="#f2c14e"):
    ax.add_patch(Circle((x, y), 2.6, fc=c, ec="black", lw=1.2, zorder=12))
    T(x, y, str(n), 9, "black", z=13)

