#pragma once
// Режим «свой сюжет».
//  * «Новая игра» при установленном моде = свой сюжет: родное вступление (миссия INTRO) не запускается,
//    маркеры родных миссий не срабатывают (CAN_PLAYER_START_MISSION в их потоках = «нет») и спрятаны.
//  * Состояние сюжета (вкл/выкл, пройдено миссий, герой) хранится рядом с каждым сохранением:
//    <Android/data/…/files>/SAStory/<имя файла сохранения>.txt. Старые сохранения без этого файла —
//    обычная игра, мод в них ничего не трогает.

#include <stdint.h>
#include <string>

namespace story
{
    struct State
    {
        bool on = false;     // свой сюжет в этой игре
        int  progress = 0;   // сколько миссий сюжета пройдено
        int  hero = 0;       // модель героя (0 — CJ)
        int  money = 0;      // (запас на будущее) сколько выдали за миссии
    };

    bool Install(void* libHandle);   // перехваты: новая игра, загрузка, сохранение, команды сценария
    const State& Get();
    bool On();
    void SetProgress(int p);
    void Frame();                    // раз в кадр игры
}
